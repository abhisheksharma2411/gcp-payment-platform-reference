/**
 * Every scenario, every control, one deterministic set of files in results/.
 *
 * Nothing here reads the host clock, so re-running produces byte-identical
 * output. That is checked by `shared/verify-package.py`.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isoOf } from '../src/clock.ts';
import { CONTROLS, controlEverythingBroken } from '../src/controls.ts';
import { SCENARIOS } from '../src/scenarios.ts';
import { SEAM_CODES } from '../src/seams.ts';
import { timelineFor } from '../src/timeline.ts';
import { renderTrace } from '../src/trace.ts';

const here = dirname(fileURLToPath(import.meta.url));
const results = join(here, '..', 'results');

const lines: string[] = [];
const p = (s = '') => lines.push(s);

p('# Payment-platform reference — scenario and control report');
p();
p('Generated by `make report`. Every number below is produced by this run.');
p('Simulated result: no cloud project, no credentials, no network.');
p();

p('## Scenarios');
p();
p('| scenario | commands | provider effects | postings | settlement lines | matched | exceptions | seam findings |');
p('|---|---:|---:|---:|---:|---:|---:|---|');

const scenarioResults = SCENARIOS.map((fn) => fn());
for (const s of scenarioResults) {
  const e = s.platform.trace.entries;
  const count = (k: string) => e.filter((x) => x.kind === k).length;
  p(
    `| \`${s.name}\` | ${count('command')} | ${count('provider_effect')} | ${count('posting')} | ` +
      `${s.settlement?.lines ?? 0} | ${s.settlement?.matched ?? 0} | ${s.settlement?.exceptions ?? 0} | ` +
      `${s.codes.length === 0 ? 'none' : s.codes.join(', ')} |`,
  );
}
p();

p('## What each scenario answered');
p();
for (const s of scenarioResults) {
  p(`**\`${s.name}\`** — ${s.description}`);
  p();
  for (const n of s.notes) p(`- ${n}`);
  p();
}

p('## Seam codes');
p();
p('| code | meaning |');
p('|---|---|');
for (const [code, meaning] of Object.entries(SEAM_CODES)) p(`| \`${code}\` | ${meaning} |`);
p();

p('## Negative controls');
p();
p('Each control must produce its code and no others.');
p();
p('| control | expected | produced | exact |');
p('|---|---|---|---|');
const controlResults = CONTROLS.map((fn) => fn());
for (const c of controlResults) {
  p(`| \`${c.name}\` | ${c.expected.join(', ')} | ${c.actual.join(', ') || 'none'} | ${c.exact ? 'yes' : 'NO'} |`);
}
const blunt = controlEverythingBroken();
p(`| \`${blunt.name}\` | *rejected* | ${blunt.actual.join(', ')} | rejected |`);
p();

const independence = controlResults.find((c) => c.name === 'posted-amount-mismatch');
p('## The independence control');
p();
p('The ledger truncates every amount to whole currency units. Both legs move');
p('together, so the ledger own balance invariant — which shares `signedMinor`');
p('with the code that wrote the postings — reports no problem.');
p();
p(`- \`Ledger.isBalanced('op_cap_1')\` → **${String(independence?.ledgerSaysBalanced)}**`);
p(`- seam auditor → **${independence?.actual.join(', ')}**`);
p();
p('The auditor compares the postings against the command that caused them.');
p('The ledger has never seen a command, so it cannot make that comparison.');
p();

p('## Audit timeline for one business operation');
p();
p('`op_auth_1` from the `ambiguous-timeout-lookup` scenario. References only;');
p('nothing here resolves a token.');
p();
p('```');
const ambiguous = scenarioResults.find((s) => s.name === 'ambiguous-timeout-lookup')!;
for (const row of timelineFor(ambiguous.platform.trace, 'op_auth_1')) {
  p(`${isoOf(row.at)}  ${row.kind.padEnd(18)} ${row.summary}`);
}
p('```');
p();

p('## Ledger');
p();
p('Account balances after `web-checkout-happy`, in minor units. DEBIT positive.');
p();
const happy = scenarioResults.find((s) => s.name === 'web-checkout-happy')!;
p('| account | balance |');
p('|---|---:|');
for (const account of happy.platform.ledger.accounts()) {
  p(`| \`${account}\` | ${happy.platform.ledger.balance(account)} |`);
}
p();

writeFileSync(join(results, 'report.md'), lines.join('\n') + '\n');

const seamJson = {
  scenarios: scenarioResults.map((s) => ({
    name: s.name,
    codes: s.codes,
    findings: s.findings,
    settlement: s.settlement,
  })),
  controls: controlResults.map((c) => ({
    name: c.name,
    expected: c.expected,
    actual: c.actual,
    exact: c.exact,
    ledgerSaysBalanced: c.ledgerSaysBalanced ?? null,
  })),
  rejectedControl: { name: blunt.name, actual: blunt.actual },
};
writeFileSync(join(results, 'seams.json'), JSON.stringify(seamJson, null, 2) + '\n');

const traceText = renderTrace(ambiguous.platform.trace, isoOf);
writeFileSync(join(results, 'trace.txt'), traceText + '\n');

console.log(`report: ${scenarioResults.length} scenarios, ${controlResults.length} controls`);
console.log('wrote results/report.md, results/seams.json, results/trace.txt');
